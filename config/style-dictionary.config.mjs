// Token build on Style Dictionary 5 (decision 0017; steps 4 and 5 of #24). The token source is DTCG:
// `$value`, `$type` (on the group where its tokens share one) and `$description`.
import { readFileSync, writeFileSync } from 'node:fs'
import StyleDictionary from 'style-dictionary'

const SOURCES = ['base', 'component', 'semantic'].map((tier) => `src/tokens/${tier}/index.json`)

// The published token types (decision 0033, #199): one nested `Tokens` type with each token's
// `$description` as JSDoc, `@deprecated` on deprecated tokens, and each group's description on the
// group. Every value is typed `string`, as `typeof tokens.json` was, so consumers see no type
// change (P7). A type literal, not interfaces: an interface isn't assignable to an index signature
// such as Record<string, string>, and the inferred JSON type was.
function tokensTypes({ dictionary }) {
  // Style Dictionary drops `$` keys from groups, so group descriptions come from the source
  const groupDescriptions = new Map()
  const collect = (node, path) => {
    for (const [key, child] of Object.entries(node)) {
      if (key.startsWith('$') || !child || typeof child !== 'object' || '$value' in child) continue
      if (typeof child.$description === 'string') groupDescriptions.set([...path, key].join('.'), child.$description)
      collect(child, [...path, key])
    }
  }
  for (const file of SOURCES) collect(JSON.parse(readFileSync(file, 'utf8')), [])

  const isToken = (node) => node && typeof node === 'object' && ('$value' in node || 'value' in node)
  const safeKey = (key) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : `'${key}'`)
  // Text inside a JSDoc block can't close it
  const text = (value) => String(value).replace(/\*\//g, '*\\/').replace(/\s+/g, ' ').trim()

  const jsdoc = (node, indent) => {
    const lines = []
    if (typeof node.$description === 'string' && node.$description.trim()) lines.push(text(node.$description))
    if (typeof node.$deprecated === 'string' || node.$deprecated === true) {
      const replacedBy = node.$extensions?.['studio.commonorigin']?.replacedBy
      const why = typeof node.$deprecated === 'string' ? text(node.$deprecated) : ''
      const use = replacedBy && !why.includes(replacedBy) ? ` Use \`${replacedBy}\`.` : ''
      lines.push(`@deprecated ${why}${use}`.trim())
    }
    if (lines.length === 0) return ''
    if (lines.length === 1 && !lines[0].startsWith('@')) return `${indent}/** ${lines[0]} */\n`
    return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`).join(`\n${indent} *\n`)}\n${indent} */\n`
  }

  const body = (node, path) => {
    const indent = '  '.repeat(path.length + 1)
    return Object.entries(node)
      .filter(([key, child]) => !key.startsWith('$') && child && typeof child === 'object')
      .map(([key, child]) =>
        isToken(child)
          ? `${jsdoc(child, indent)}${indent}${safeKey(key)}: string;\n`
          : `${jsdoc({ $description: groupDescriptions.get([...path, key].join('.')) }, indent)}${indent}${safeKey(key)}: {\n${body(child, [...path, key])}${indent}};\n`
      )
      .join('')
  }

  // No timestamp, so a build with no token changes leaves the file untouched (defect 8)
  return `/**
 * Do not edit directly, this file was auto-generated by npm run build:tokens.
 */

/** Every design token, by tier. Hover a token for when to use it. */
export type Tokens = {
${body(dictionary.tokens, [])}};
`
}

// Deprecation is the DTCG `$deprecated` field (decision 0033). The CSS format prints only the
// description as a comment, so a deprecated token's comment carries the deprecation instead.
// It runs on the CSS platform only: platforms work on their own copy of the tokens.
function deprecationComments(dictionary) {
  const walk = (node) => {
    for (const [key, child] of Object.entries(node)) {
      if (key.startsWith('$') || !child || typeof child !== 'object') continue
      if ('$value' in child) {
        if (typeof child.$deprecated === 'string') child.$description = `Deprecated: ${child.$deprecated}`
      } else walk(child)
    }
  }
  walk(dictionary)
  return dictionary
}

const sd = new StyleDictionary({
  // The three tier folders, in this order so output order stays stable
  source: ['src/tokens/base/**/*.json', 'src/tokens/component/**/*.json', 'src/tokens/semantic/**/*.json'],
  usesDtcg: true,
  log: { warnings: 'error' },
  hooks: {
    formats: { 'typescript/tokens-types': tokensTypes },
    preprocessors: { 'deprecation-comments': deprecationComments },
  },
  // No value transforms yet. Style Dictionary 5's built-in groups match on token type, so `js` and
  // `css` would rewrite every colour (#16191C -> #16191c, transparent -> #00000000). Step 4 must
  // leave values unchanged, so each platform names only the transform it needs; value transforms
  // come back deliberately, with their own diff, in later steps.
  platforms: {
    tokens: {
      transforms: ['name/camel'],
      buildPath: 'src/styles/',
      files: [{ format: 'json/nested', destination: 'tokens.json' }],
    },
    // Published as @common-origin/design-system/tokens.css (decision 0017 §4). Every variable keeps
    // its tier after the `co-` prefix (decision 0024), and references stay as var() chains.
    custom: {
      transforms: ['name/kebab'],
      prefix: 'co',
      preprocessors: ['deprecation-comments'],
      buildPath: 'src/styles/',
      files: [{ format: 'css/variables', destination: 'tokens.css', options: { outputReferences: true } }],
    },
    typescript: {
      transforms: ['name/camel'],
      buildPath: 'src/styles/',
      files: [{ format: 'typescript/tokens-types', destination: 'tokens.ts' }],
    },
  },
})

await sd.buildAllPlatforms()

// Token modes (decision 0032). src/tokens/resolver.json describes them as DTCG Resolver modifiers;
// each context is a file that overrides only the $value of tokens in the groups the mode may change.
// tokens.css gets one block per context. A CSS variable that references another is resolved where
// it's declared (decision 0041), so a block redeclares every token whose resolved value changes in
// that context, the overridden tokens and the aliases built on them alike, keeping references as
// var(). Every block declares the same tokens, so contexts nest, and a `default` block resets a
// region nested inside another context.
const resolver = JSON.parse(readFileSync('src/tokens/resolver.json', 'utf8'))
const tiers = () => Object.assign({}, ...SOURCES.map((file) => JSON.parse(readFileSync(file, 'utf8'))))

// Each context is merged in memory: as a second source, an overridden token would collide
function withContext(sources) {
  const tokens = tiers()
  const apply = (node, target, path) => {
    for (const [key, child] of Object.entries(node)) {
      if (key.startsWith('$') || !child || typeof child !== 'object') continue
      const next = target?.[key]
      if (!next) throw new Error(`Mode override ${[...path, key].join('.')} has no token to override`)
      if ('$value' in child) next.$value = child.$value
      else apply(child, next, [...path, key])
    }
  }
  for (const { $ref } of sources) apply(JSON.parse(readFileSync(`src/tokens/${$ref}`, 'utf8')), tokens, [])
  return tokens
}

const modeDictionary = (tokens, files = []) =>
  new StyleDictionary({
    tokens,
    usesDtcg: true,
    // A block filters to the changed tokens, so its var() references point at variables declared in
    // the :root block of the same file. Style Dictionary warns about every such reference.
    log: { warnings: 'disabled', verbosity: 'silent' },
    hooks: { preprocessors: { 'deprecation-comments': deprecationComments } },
    platforms: {
      css: { transforms: ['name/kebab'], prefix: 'co', preprocessors: ['deprecation-comments'], files },
    },
  })

async function resolvedValues(tokens) {
  const { allTokens } = await modeDictionary(tokens).getPlatformTokens('css')
  return new Map(allTokens.map((token) => [token.path.join('.'), JSON.stringify(token.$value)]))
}

async function modeBlock(selector, tokens, changed) {
  const [{ output }] = await modeDictionary(tokens, [
    {
      format: 'css/variables',
      destination: 'mode.css',
      filter: (token) => changed.has(token.path.join('.')),
      options: { outputReferences: true, selector, showFileHeader: false },
    },
  ]).formatPlatform('css')
  return output
}

const blocks = []
for (const [name, modifier] of Object.entries(resolver.modifiers)) {
  const baseline = await resolvedValues(tiers())
  const contexts = []
  for (const [context, sources] of Object.entries(modifier.contexts)) {
    if (context === modifier.default) continue
    const tokens = withContext(sources)
    const values = await resolvedValues(tokens)
    const changed = new Set([...values].filter(([path, value]) => baseline.get(path) !== value).map(([path]) => path))
    contexts.push({ context, tokens, changed })
  }
  const all = new Set(contexts.flatMap(({ changed }) => [...changed]))
  blocks.push(`/* Mode: ${name} (decision 0032). ${modifier.description} */`)
  blocks.push(await modeBlock(`[data-co-${name}="${modifier.default}"]`, tiers(), all))
  // Every block declares every token any context changes, so contexts nest: a compact region
  // inside a comfortable one gets compact's value even where compact matches the default
  for (const { context, tokens } of contexts) blocks.push(await modeBlock(`[data-co-${name}="${context}"]`, tokens, all))
}

const css = readFileSync('src/styles/tokens.css', 'utf8')
writeFileSync('src/styles/tokens.css', `${css.trimEnd()}\n\n${blocks.map((block) => block.trim()).join('\n\n')}\n`)
